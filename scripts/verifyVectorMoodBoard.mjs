import assert from "node:assert/strict";
import { mkdtemp, readFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import sharp from "sharp";
import { startVectorQaServer } from "./vectorQaServer.mjs";

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const directory = await mkdtemp(path.join(tmpdir(), "newtnode-vector-mood-qa-"));
const svg = await readFile(new URL("../test/fixtures/vector-design.svg", import.meta.url));
const png = await sharp(svg).png().toBuffer();
const browser = await chromium.launch({ headless: true, channel: process.env.VECTOR_BROWSER_CHANNEL || "chrome" });
const fixtureServer = await startVectorQaServer({ svg, png });
const errors = [], apiCalls = [];
try {
  const page = await browser.newPage({ viewport: { width: 1200, height: 1100 } });
  page.on("pageerror", error => errors.push(error.message));
  await page.route(/^https?:\/\/[^/]+\/api\//, route => { apiCalls.push(route.request().url()); return route.abort(); });
  await page.goto(`${fixtureServer.url}/test/browser/vector.html`);
  const calls = () => page.getByLabel("Provider calls").textContent().then(JSON.parse);
  const waitCount = n => page.waitForFunction(n => JSON.parse(document.querySelector('[aria-label="Vector state"]').textContent).resultItems.length === n, n);
  await page.getByRole("checkbox", { name: "Connect Mood Board", exact: true }).check();
  assert.equal((await calls()).generate, 0);
  assert.equal(await page.locator('[data-port-key="qa-vector:transferIn"]').count(), 1, "visible input retains one connection anchor");
  assert.equal(await page.getByRole("button", { name: "Settings", exact: true }).count(), 0);
  const port = page.locator('button[data-port-key="qa-vector:transferIn"]');
  assert.equal(await port.isEnabled(), true);
  assert.equal(await page.locator('[data-port-id="styleIn"]').count(), 0);
  await page.getByLabel("Vector quality").selectOption("high");
  await page.waitForFunction(() => document.querySelector(".vector-generate").textContent.includes("$0.32"));
  await page.getByRole("checkbox", { name: "Empty Mood Board", exact: true }).check();
  assert.equal(await page.locator(".vector-generate").isDisabled(), true);
  await page.getByRole("checkbox", { name: "Empty Mood Board", exact: true }).uncheck();
  await page.getByRole("checkbox", { name: "Connect source", exact: true }).check();
  await page.locator(".vector-generate").click(); await waitCount(1);
  const generated = (await calls()).last;
  assert.deepEqual(generated.images.map(image => image.url), ["/uploads/vector-qa/source.png", "/uploads/vector-qa/mood.png"]);
  assert.match(generated.prompt, /Reference image 1: SUBJECT \/ CONTENT/);
  assert.match(generated.prompt, /Reference image 2: MOOD BOARD/);
  assert.match(generated.prompt, /Do not copy the mood board's subjects/);
  await page.getByRole("button", { name: "Save / Reopen", exact: true }).click();
  assert.equal((await calls()).generate, 1);
  await page.locator(".node-card.vector").screenshot({ path: path.join(directory, "mood-board-desktop.png") });
  await page.setViewportSize({ width: 420, height: 1100 });
  await page.locator(".node-card.vector").screenshot({ path: path.join(directory, "mood-board-narrow.png") });
  assert.equal(await page.locator(".node-card.vector").evaluate(el => el.scrollWidth > el.clientWidth + 2), false);
  await page.getByLabel("Vector task").selectOption("vectorize");
  assert.equal(await port.isDisabled(), true);
  await page.getByRole("checkbox", { name: "Empty Mood Board", exact: true }).check();
  assert.equal(await page.locator(".vector-generate").isEnabled(), true, "unused Mood Board cannot block conversion");
  await page.locator(".vector-generate").click(); await waitCount(2);
  assert.equal((await calls()).last.mode, "vectorize");
  assert.equal((await calls()).last.images.length, 1);
  assert.equal((await calls()).last.prompt, undefined);
  await page.getByRole("checkbox", { name: "Empty Mood Board", exact: true }).uncheck();
  await page.getByLabel("Vector task").selectOption("generate");
  assert.equal(await port.isEnabled(), true);
  assert.equal((await calls()).generate, 2, "mode changes never generate");
  await page.getByRole("checkbox", { name: "Connect Mood Board", exact: true }).uncheck();
  await page.getByRole("checkbox", { name: "Connect source", exact: true }).uncheck();
  await page.waitForFunction(() => document.querySelector(".vector-generate").textContent.includes("$0.20"));
  assert.deepEqual(errors, []); assert.deepEqual(apiCalls, []);
  console.log(JSON.stringify({ passed: true, screenshots: directory, providerCalls: 0 }));
} finally { await browser.close(); await fixtureServer.close(); }
