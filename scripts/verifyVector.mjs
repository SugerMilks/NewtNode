import assert from "node:assert/strict";
import { mkdtemp } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import sharp from "sharp";
import { startVectorQaServer } from "./vectorQaServer.mjs";

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const directory = await mkdtemp(path.join(tmpdir(), "newtnode-vector-qa-"));
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 640 640"><rect width="640" height="640" fill="#f4edda"/><path d="M120 360Q80 140 290 170Q400 180 480 100Q530 250 400 310Q330 350 450 420Q470 500 370 510Q190 490 120 360Z" fill="#184c45"/><path d="M185 320Q260 250 360 280Q300 340 370 405Q250 430 185 320Z" fill="#ed8662"/><circle cx="245" cy="215" r="14" fill="#f4edda"/><text x="320" y="580" text-anchor="middle" font-family="sans-serif" font-size="50" font-weight="700" fill="#184c45">NEWT STUDIO</text></svg>`;
const png = await sharp(Buffer.from(svg)).png().toBuffer();
const browser = await chromium.launch({ headless: true, channel: process.env.VECTOR_BROWSER_CHANNEL || "chrome" });
const fixtureServer = await startVectorQaServer({ svg, png });
const errors = [], apiCalls = [];
try {
  const page = await browser.newPage({ viewport: { width: 1300, height: 1100 } });
  page.on("pageerror", error => errors.push(error.message));
  await page.route(/^https?:\/\/[^/]+\/api\//, route => { apiCalls.push(route.request().url()); return route.abort(); });
  await page.goto(`${fixtureServer.url}/test/browser/vector.html`);
  const state = () => page.getByLabel("Vector state").textContent().then(JSON.parse);
  const calls = () => page.getByLabel("Provider calls").textContent().then(JSON.parse);
  const waitCount = count => page.waitForFunction(n => JSON.parse(document.querySelector('[aria-label="Vector state"]').textContent).resultItems.length === n, count);
  assert.equal(await page.getByRole("button", { name: "Settings", exact: true }).count(), 0);
  assert.equal(await page.getByLabel("Design direction").isVisible(), true, "legacy collapsed settings are always visible");
  await page.getByLabel("Design direction").selectOption("logo");
  await page.getByLabel("Lettering", { exact: true }).fill("NEWT STUDIO");
  await page.getByLabel("Palette", { exact: true }).fill("Forest green, cream and coral");
  await page.getByLabel("Vector seed").fill("0");
  await page.locator(".vector-generate").evaluate(button => { button.click(); button.click(); });
  await waitCount(1);
  assert.equal((await calls()).generate, 1, "double click submits exactly once");
  assert.equal((await calls()).last.seed, 0); assert.match((await calls()).last.prompt, /NEWT STUDIO/);
  await page.waitForFunction(() => document.querySelector(".vector-monitor img")?.naturalWidth > 0);
  const monitor = page.locator(".vector-monitor"), previewImage = monitor.locator("img");
  const card = page.locator(".node-card.vector");
  assert.equal(Math.round((await card.boundingBox()).width), 900, "Vector is about 2.4 times its former width");
  assert.ok(await page.locator(".vector-node-body").evaluate(body => {
    const preview = body.querySelector(".vector-monitor").getBoundingClientRect();
    const controls = body.querySelector(".vector-controls").getBoundingClientRect();
    const compose = body.querySelector(".vector-compose").getBoundingClientRect();
    const settings = body.querySelector(".vector-settings").getBoundingClientRect();
    const footer = body.querySelector(".vector-footer").getBoundingClientRect();
    return Math.abs(preview.width - controls.width) < 1 && preview.bottom < controls.top && compose.right < settings.left && footer.top >= controls.bottom;
  }), "full-width preview sits above two control columns and the generation footer");
  assert.equal(await card.locator("[data-port-key]").count(), 4, "all original inputs and the output retain real anchors");
  assert.equal(await page.locator(".vector-preview-toolbar").count(), 0);
  for (const name of ["Vector zoom", "Preview background", "Open PNG preview"]) assert.equal(await page.getByLabel(name, { exact: true }).count(), 0);
  assert.equal((await state()).previewBackground, "dark", "fixture exercises a legacy background setting");
  assert.ok(await monitor.evaluate(el => getComputedStyle(el).backgroundImage.includes("conic-gradient")), "checkerboard overrides old background choices");
  assert.equal(await monitor.evaluate(el => el.scrollWidth > el.clientWidth || el.scrollHeight > el.clientHeight), false, "fitted preview never scrolls");
  assert.equal(await previewImage.evaluate(el => getComputedStyle(el).objectFit), "contain");
  await previewImage.click(); assert.equal(await page.getByRole("dialog").count(), 0, "single click does not open the preview");
  await page.evaluate(() => { window.vectorQaDoubleClicks = 0; window.addEventListener("dblclick", () => window.vectorQaDoubleClicks++); });
  const pointerDowns = await page.getByLabel("Node pointer downs").textContent();
  await previewImage.dblclick();
  assert.equal(await page.getByRole("dialog").locator("img").getAttribute("src"), (await state()).resultItems[0].url, "double-click expands the full-resolution PNG");
  assert.equal(await page.evaluate(() => window.vectorQaDoubleClicks), 0, "double-click does not reach the canvas");
  assert.equal(await page.getByLabel("Node pointer downs").textContent(), pointerDowns, "expanding does not start a node drag");
  await page.getByRole("button", { name: "Close preview", exact: true }).click();
  await previewImage.press("Enter"); assert.equal(await page.getByRole("dialog").count(), 1, "preview stays keyboard accessible");
  await page.getByRole("button", { name: "Close preview", exact: true }).click();
  assert.equal((await calls()).generate, 1, "preview gestures never generate");
  await page.locator(".node-card.vector").screenshot({ path: path.join(directory, "vector-expanded.png") });
  await page.setViewportSize({ width: 420, height: 1000 });
  assert.ok((await card.boundingBox()).width < 420, "node fits a narrow viewport");
  assert.ok(await page.locator(".vector-controls").evaluate(el => {
    const compose = el.querySelector(".vector-compose").getBoundingClientRect(), settings = el.querySelector(".vector-settings").getBoundingClientRect();
    return settings.top > compose.bottom && el.scrollWidth <= el.clientWidth;
  }), "narrow layout stacks sections without overflowing");
  await card.screenshot({ path: path.join(directory, "vector-generate-narrow.png") });
  await page.setViewportSize({ width: 1300, height: 1100 });
  assert.equal(await page.locator(".vector-export-row, .vector-note, .vector-model-caption, .node-card.vector a[download]").count(), 0);
  const saved = (await state()).resultItems[0];
  assert.match(await (await page.request.get(`${fixtureServer.url}${saved.svgUrl}`)).text(), /<svg/);
  assert.equal((await sharp(await (await page.request.get(`${fixtureServer.url}${saved.url}`)).body()).metadata()).format, "png");
  await page.getByRole("button", { name: "Save / Reopen", exact: true }).click();
  assert.equal((await state()).resultItems[0].svgUrl.includes(".svg"), true); assert.equal((await calls()).generate, 1);
  assert.ok(await monitor.evaluate(el => getComputedStyle(el).backgroundImage.includes("conic-gradient")), "checkerboard survives reopening older nodes");
  assert.equal(await page.getByLabel("Design direction").isVisible(), true);
  await page.getByRole("checkbox", { name: "Slow response" }).check();
  await page.locator(".vector-generate").click();
  await page.getByRole("button", { name: "Stop waiting; provider work may still finish and be billed" }).click();
  assert.equal((await state()).vectorJob.status, "uncertain");
  await page.waitForTimeout(1650); assert.equal((await state()).resultItems.length, 1, "late result cannot overwrite after Stop waiting");
  await page.getByRole("button", { name: "Check existing request; does not generate again" }).click();
  await waitCount(2); assert.equal((await calls()).generate, 2); assert.equal((await calls()).check, 1);
  await page.getByRole("button", { name: "Select Newt studio mark", exact: true }).first().click();
  const selected = (await state()).resultUrl;
  await page.locator(".vector-generate").click();
  await page.getByRole("button", { name: "Select Newt studio mark", exact: true }).nth(1).click();
  const browsed = (await state()).resultUrl;
  const dropTarget = page.getByLabel("Canvas drop target");
  await dropTarget.evaluate(el => Object.assign(el.style, { position: "fixed", right: "24px", top: "120px" }));
  await page.locator(".vector-variants button").nth(1).dragTo(dropTarget);
  assert.equal(JSON.parse(await page.getByLabel("Dropped output").textContent()).url, browsed, "saved thumbnails remain draggable during generation");
  await dropTarget.evaluate(el => Object.assign(el.style, { position: "", right: "", top: "" }));
  assert.notEqual(browsed, selected); await waitCount(3);
  assert.equal((await state()).resultUrl, browsed, "completion preserves intervening variant selection");
  await page.locator(".vector-generate").click();
  await page.getByRole("button", { name: "Save / Reopen", exact: true }).click();
  await page.waitForTimeout(1650);
  assert.equal((await state()).resultItems.length, 3, "unmounted request cannot write after reopen");
  assert.equal((await state()).vectorJob.status, "uncertain");
  await page.getByRole("button", { name: "Check existing request; does not generate again" }).click(); await waitCount(4);
  await page.locator(".vector-generate").click();
  await page.getByRole("button", { name: "Switch project", exact: true }).click();
  await page.waitForTimeout(1650);
  assert.equal((await state()).resultItems.length, 0, "old scope cannot write into new project with same node id");
  assert.equal(await page.locator(".vector-generate").isDisabled(), false, "new project clears local busy state");
  await page.getByRole("checkbox", { name: "Slow response" }).uncheck();
  await page.getByRole("checkbox", { name: "Connect source" }).check();
  await page.getByLabel("Vector task").selectOption("vectorize");
  await page.getByLabel("Conversion detail").selectOption("simple");
  await page.locator(".vector-generate").click(); await waitCount(1);
  assert.equal((await calls()).last.mode, "vectorize"); assert.equal((await calls()).last.vectorizeMode, "simple");
  assert.equal((await calls()).last.prompt, undefined); assert.equal((await calls()).last.seed, undefined);
  await page.getByRole("button", { name: "Source", exact: true }).click();
  await page.waitForFunction(() => document.querySelector(".vector-monitor img")?.naturalWidth > 0);
  await previewImage.dblclick();
  assert.equal(await page.getByRole("dialog").locator("img").getAttribute("src"), "/uploads/vector-qa/source.png", "source comparison expands the image actually displayed");
  await page.getByRole("button", { name: "Close preview", exact: true }).click();
  await dropTarget.evaluate(el => Object.assign(el.style, { position: "fixed", right: "24px", top: "120px" }));
  await page.locator(".vector-monitor img").dragTo(dropTarget);
  assert.equal(JSON.parse(await page.getByLabel("Dropped output").textContent()).url, "/uploads/vector-qa/source.png", "source comparison drags the image actually displayed");
  await dropTarget.evaluate(el => Object.assign(el.style, { position: "", right: "", top: "" }));
  await page.getByRole("button", { name: "SVG", exact: true }).click();
  await page.getByRole("checkbox", { name: "Fail request" }).check();
  await page.locator(".vector-generate").click();
  await page.getByRole("alert").filter({ hasText: "Mock provider rejection" }).waitFor();
  assert.ok((await state()).vectorJob, "HTTP400 cannot discard a possibly paid request receipt");
  assert.equal((await state()).resultItems.length, 1);
  await page.getByRole("button", { name: "Check existing request; does not generate again" }).click();
  assert.equal((await state()).vectorJob.status, "failed");
  await page.setViewportSize({ width: 420, height: 1000 });
  await page.locator(".node-card.vector").screenshot({ path: path.join(directory, "vector-narrow.png") });
  assert.equal(await page.locator(".node-card.vector").evaluate(el => el.scrollWidth > el.clientWidth + 2), false, "node controls fit a narrow card");
  assert.deepEqual(errors, []); assert.deepEqual(apiCalls, []);
  console.log(JSON.stringify({ passed: true, checks: ["always-visible settings", "removed preview toolbar", "legacy checkerboard/fit", "double-click/keyboard expansion", "source comparison expansion/drag", "prompt controls", "saved SVG/PNG assets", "save/reopen", "stop and recover", "selection preservation", "unmount", "scope change", "vectorize", "failure receipt", "narrow layout"], screenshots: directory, providerCalls: 0 }, null, 2));
} finally { await browser.close(); await fixtureServer.close(); }
