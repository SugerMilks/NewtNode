import assert from "node:assert/strict";
import { mkdtemp } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import sharp from "sharp";
import { createVectorLayerService } from "../server/vector-layer-service.js";
import { startVectorQaServer } from "./vectorQaServer.mjs";

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const directory = await mkdtemp(path.join(tmpdir(), "newtnode-vector-organization-qa-"));
const svg = '<svg xmlns="http://www.w3.org/2000/svg" width="400" height="300"><path id="paper" d="M0 0H400V300H0Z" fill="#fff"/><rect id="body" x="100" y="60" width="200" height="160" rx="20" fill="#2d7371"/><circle id="eye-left" cx="160" cy="120" r="12" fill="#fff"/><circle id="eye-right" cx="240" cy="120" r="12" fill="#fff"/><path id="mouth" d="M150 165Q200 205 250 165" fill="none" stroke="#fff" stroke-width="8"/><g id="seal"><circle id="badge" cx="300" cy="220" r="28" fill="#e8c341"/></g></svg>';
const png = await sharp(Buffer.from(svg)).png().toBuffer();
const assets = new Map(), errors = [], forbidden = [], history = [];
let setups = 0;
const service = createVectorLayerService({ readSource: async url => assets.get(url) || Buffer.from(svg), saveAssets: async (body, art) => {
  const base = `/outputs/vector-qa/${body.requestId}`;
  assets.set(`${base}.svg`, Buffer.from(art.svg)); assets.set(`${base}.png`, art.png); assets.set(`${base}-alpha.png`, art.alpha);
  return { url: `${base}.png`, svgUrl: `${base}.svg`, alphaUrl: `${base}-alpha.png` };
}, recordHistory: async item => history.push(item) });
const fixture = await startVectorQaServer({ svg, png, assets, service: { ...service, inspect: body => { if (body.prepareBackground) setups++; return service.inspect(body); } } });
const browser = await chromium.launch({ headless: true, channel: "chrome" });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(15000); page.on("pageerror", error => errors.push(error.message)); page.on("dialog", dialog => dialog.accept());
  await page.route(/^https?:\/\/[^/]+\/api\//, route => { forbidden.push(route.request().url()); return route.abort(); });
  await page.goto(`${fixture.url}/test/browser/vector.html`);
  const button = name => page.getByRole("button", { name, exact: true });
  const modal = page.getByRole("dialog", { name: "Vector Layers editor" });
  const row = key => page.locator(`[data-layer-key="${key}"]`);
  const state = () => page.getByLabel("Vector state").textContent().then(JSON.parse);
  const ops = async () => (await state()).vectorLayerDrafts[0]?.operations || [];
  const ready = () => page.waitForFunction(() => document.querySelector('[aria-label="Vector layers"]')?.getAttribute("aria-busy") === "false");
  const pixel = (x, y) => page.locator(".vle-artwork img").evaluate(async (img, [x, y]) => { await img.decode(); const canvas = document.createElement("canvas"); canvas.width = 400; canvas.height = 300; const ctx = canvas.getContext("2d"); ctx.drawImage(img, 0, 0, 400, 300); return [...ctx.getImageData(x, y, 1, 1).data]; }, [x, y]);
  const open = async () => { await button("Edit Artwork").click(); await ready(); };
  await page.locator(".vector-generate").click(); await open();
  assert.equal((await state()).resultItems[0].vectorLayersPrepared, true);
  assert.equal((await state()).resultItems[0].vectorGroupsPrepared, true);
  assert.equal((await ops()).length, 1); assert.equal(setups, 1);
  const autoBackground = (await ops())[0].operations.find(op => op.type === "group" && op.name === "Background");
  assert.equal(await row(autoBackground.id).locator(".vle-layer-name").textContent(), "Background");
  assert.equal((await pixel(0, 0))[3], 0); assert.deepEqual(await pixel(160, 120), [255, 255, 255, 255]);
  await button("Undo layer edit").click(); await ready(); assert.equal((await pixel(0, 0))[3], 255);
  await button("Redo layer edit").click(); await ready(); assert.equal((await pixel(0, 0))[3], 0);
  await page.getByRole("switch", { name: "Background visible" }).check(); await ready();
  await button("Cancel").click(); await modal.waitFor({ state: "detached" });
  assert.deepEqual((await state()).vectorLayerDrafts, []);
  await button("Save / Reopen").click(); await open(); assert.equal(setups, 1); assert.equal((await pixel(0, 0))[3], 255, "reopening respects Undo/Cancel instead of hiding the backdrop again");
  await row("paper").click(); await button("Mark selected objects as background").click(); await ready();
  await page.getByRole("switch", { name: "Background visible" }).uncheck(); await ready();

  const before = await ops();
  await button("Organize loose layers into folders without changing their stacking order").click(); await ready();
  assert.equal((await ops()).length, before.length + 1);
  const folder = (await ops()).at(-1).operations[0];
  assert.equal(folder.name, "Artwork 1"); assert.equal(await row(folder.id).locator(".vle-group-count").textContent(), "4");
  assert.equal(await row("seal").count(), 1); assert.equal(await page.locator(".vle-layer-row").count(), 3);
  assert.equal(await button("Organize loose layers into folders without changing their stacking order").isDisabled(), true);
  await button("Undo layer edit").click(); await ready(); assert.equal(await page.locator(".vle-layer-row").count(), 6);
  await button("Redo layer edit").click(); await ready(); await button("Expand all groups").click();
  assert.equal(await row("badge").count(), 1); await button("Collapse all groups").click(); assert.equal(await row("badge").count(), 0);
  await row(folder.id).click(); await page.keyboard.press("Meta+Shift+g"); await ready();
  assert.equal(await row(folder.id).count(), 0);
  await row("eye-left").click(); await row("mouth").click({ modifiers: ["Shift"] });
  assert.equal(await page.locator('.vle-layer-row[aria-selected="true"]').count(), 3);
  await page.keyboard.press("Meta+g"); await ready();
  const manual = (await ops()).at(-1).id;
  await page.getByLabel(`Layer name ${manual}`, { exact: true }).fill("Face details");
  await page.getByLabel(`Layer name ${manual}`, { exact: true }).press("Enter"); await ready();
  assert.equal(await row(manual).locator(".vle-layer-name").textContent(), "Face details");
  await row(manual).click(); await page.locator(".vle-selection").waitFor();
  await page.locator(".vle-artwork").focus(); await page.keyboard.press("Shift+ArrowRight"); await ready();
  assert.equal(await button("Ungroup").isDisabled(), false, "a moved group can still be ungrouped");
  await button("Ungroup").click(); await ready(); assert.equal(await row(manual).count(), 0);
  await button("Undo layer edit").click(); await ready(); assert.equal(await row(manual).count(), 1);
  await button("Collapse all groups").click();
  await modal.screenshot({ path: path.join(directory, "groups-desktop.png") });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await modal.evaluate(el => el.scrollWidth <= el.clientWidth + 1));
  assert.ok(await page.locator(".vle-group-tools").evaluate(el => el.scrollWidth <= el.clientWidth + 1));
  await modal.screenshot({ path: path.join(directory, "groups-mobile.png") });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await modal.getByRole("button", { name: "Save Version", exact: true }).click(); await modal.waitFor({ state: "detached" });
  const edited = (await state()).resultItems[1]; assert.equal(edited.vectorLayersPrepared, true); assert.equal(edited.cost.amountUsd, 0);
  assert.match(assets.get(edited.svgUrl).toString(), /Face details/);
  assert.equal((await sharp(assets.get(edited.url)).ensureAlpha().raw().toBuffer())[3], 0);
  await button("Save / Reopen").click(); await open(); assert.equal(setups, 1); assert.equal(await row(manual).count(), 1);
  const calls = JSON.parse(await page.getByLabel("Provider calls").textContent()); assert.equal(calls.generate, 1); assert.equal(calls.naming || 0, 0);
  assert.deepEqual(errors, []); assert.deepEqual(forbidden, []);
  console.log(JSON.stringify({ ok: true, directory, localSaves: history.length, paidCalls: 0, checks: ["automatic backdrop only", "white detail retained", "single-step Undo", "Cancel/reopen respects choices", "organize folders", "collapse/expand", "range select", "group/ungroup shortcuts", "rename", "move/ungroup", "desktop/mobile", "saved alpha/groups", "no repeated setup"] }, null, 2));
} finally { await browser.close(); await fixture.close(); }
