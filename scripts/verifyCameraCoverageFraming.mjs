import assert from "node:assert/strict";
import path from "node:path";
import sharp from "sharp";
import { coverageTravelPosition } from "../src/cameraCoverage.js";

export async function verifyCameraCoverageFraming(page, screenshots) {
  await page.reload();
  const state = () => page.locator('output[aria-label="State"]').textContent().then(JSON.parse);
  const calls = () => page.locator('output[aria-label="Calls"]').textContent().then(JSON.parse);
  const protect = page.getByRole("switch", { name: "Protect Framing" });
  const room = page.getByRole("slider", { name: "Extra Room" });
  const preset = page.getByRole("combobox", { name: "Camera pass preset" });
  const canvas = page.locator(".coverage-diagram canvas");
  await canvas.waitFor();
  assert.equal(await protect.getAttribute("aria-checked"), "false");
  assert.equal(await room.count(), 0);
  await preset.selectOption("Close Coverage");
  const original = (await state()).coveragePoses;
  const before = await canvas.screenshot();
  await protect.click();
  assert.equal(await room.inputValue(), "20");
  assert.equal(Number(await page.getByRole("spinbutton", { name: "Distance", exact: true }).inputValue()), 1.2);
  assert.ok(!before.equals(await canvas.screenshot()), "diagram shows the adjusted camera distance");
  assert.deepEqual((await state()).coveragePoses, original, "protection does not rewrite saved raw poses");
  await room.fill("30");
  assert.equal(Number(await page.getByRole("spinbutton", { name: "Distance", exact: true }).inputValue()), 1.3);
  await protect.click();
  assert.equal(Number(await page.getByRole("spinbutton", { name: "Distance", exact: true }).inputValue()), 0.7);
  await protect.click();
  await page.getByRole("button", { name: "Master", exact: true }).click();
  assert.equal(Number(await page.getByRole("spinbutton", { name: "Distance", exact: true }).inputValue()), 1);
  assert.equal(await page.getByRole("spinbutton", { name: "Distance", exact: true }).isDisabled(), true);
  await preset.selectOption("Close Coverage");
  await page.getByRole("button", { name: "Save / Reopen", exact: true }).click();
  assert.equal(await protect.getAttribute("aria-checked"), "true"); assert.equal(await room.inputValue(), "30");
  await page.getByRole("checkbox", { name: "Hold jobs", exact: true }).check();
  await page.getByRole("button", { name: "Generate Camera Pass", exact: true }).click();
  const request = (await calls()).lastStart;
  assert.equal(request.protectFraming, true); assert.equal(request.framingRoom, 30);
  await room.fill("5"); await protect.click();
  await page.getByRole("checkbox", { name: "Hold jobs", exact: true }).uncheck();
  await page.getByRole("button", { name: "Check existing request; never submits again" }).evaluateAll(buttons => buttons[0]?.click());
  await page.waitForFunction(() => JSON.parse(document.querySelector('output[aria-label="State"]').textContent).coveragePasses.length === 1);
  const pass = (await state()).coveragePasses[0];
  assert.equal(pass.protectFraming, true); assert.equal(pass.framingRoom, 30);
  assert.ok(pass.trajectory.slice(2).every(p => p.distance >= 1.3), "submitted protection survives later settings changes");
  assert.equal((await state()).coverageProtectFraming, false); assert.equal((await state()).coverageFramingRoom, 5);
  await page.getByRole("combobox", { name: "Camera movement" }).selectOption("travel");
  await protect.click(); await room.fill("40");
  const xyz = coverageTravelPosition((await state()).coveragePoses[1]);
  assert.equal(Number(await page.getByRole("spinbutton", { name: "Slide", exact: true }).inputValue()), Number(xyz.slide.toFixed(3)));
  assert.equal(Number(await page.getByRole("spinbutton", { name: "Dolly", exact: true }).inputValue()), 1.4);
  await page.getByRole("spinbutton", { name: "Dolly", exact: true }).fill("0.6");
  assert.equal(Number(await page.getByRole("spinbutton", { name: "Dolly", exact: true }).inputValue()), 1.4, "protected depth cannot move inward");
  await page.getByRole("application", { name: "Camera slide and boom" }).focus();
  await page.keyboard.press("ArrowRight");
  assert.ok(Math.abs(coverageTravelPosition((await state()).coveragePoses[1]).dolly - 1.4) < 1e-9);
  await page.screenshot({ path: path.join(screenshots, "framing-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 1100 });
  await page.locator(".coverage-framing").scrollIntoViewIfNeeded();
  await page.locator(".coverage-settings").screenshot({ path: path.join(screenshots, "framing-mobile.png") });
  const pixels = await sharp(await canvas.screenshot()).stats();
  assert.ok(pixels.channels.some(c => c.stdev > 15), "protected travel diagram renders at mobile size");
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.setViewportSize({ width: 1440, height: 1400 });
}
