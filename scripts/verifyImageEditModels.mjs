import assert from "node:assert/strict";
import { mkdtemp } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createServer } from "vite";

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const server = await createServer({
  root: fileURLToPath(new URL("../", import.meta.url)),
  configFile: fileURLToPath(new URL("../test/browser/storyboard.config.js", import.meta.url)),
  server: { host: "127.0.0.1", port: 0, strictPort: false, hmr: false }, logLevel: "error"
});
let browser;
try {
  await server.listen();
  browser = await chromium.launch({ headless: true, channel: "chrome" });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, hasTouch: true });
  const errors = [], apiCalls = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.route(/^https?:\/\/[^/]+\/api\//, route => { apiCalls.push(route.request().url()); return route.abort(); });
  const url = `http://127.0.0.1:${server.httpServer.address().port}/test/browser/image-edit.html`;
  const screenshots = await mkdtemp(path.join(tmpdir(), "newtnode-image-edit-models-"));
  const open = async (portrait = false, provider = "fal") => {
    await page.goto(url);
    await page.getByLabel("Available edit provider").selectOption(provider);
    await page.getByRole("button", { name: portrait ? "Open portrait" : "Open landscape", exact: true }).click();
    const advanced = page.getByRole("button", { name: "Advanced Edit", exact: true });
    assert.equal(await advanced.textContent(), "Advanced Edit");
    for (const property of ["color", "backgroundColor", "borderTopColor"]) {
      const channels = await advanced.evaluate((element, key) => getComputedStyle(element)[key].match(/[\d.]+/g).slice(0, 3).map(Number), property);
      assert.ok(channels.every(value => value === channels[0]), "Advanced Edit uses neutral gray styling");
    }
    const buttonBounds = await advanced.boundingBox(), toolsBounds = await page.getByLabel("Layout image editing tools").boundingBox();
    assert.ok(buttonBounds.width > 110 && buttonBounds.x >= 0 && buttonBounds.x + buttonBounds.width <= page.viewportSize().width);
    if (page.viewportSize().width > 760) assert.ok(toolsBounds.x - buttonBounds.x - buttonBounds.width >= 12, "advanced editing is spaced apart from basic tools");
    await page.screenshot({ path: path.join(screenshots, `advanced-edit-entry-${page.viewportSize().width > 760 ? "desktop" : "mobile"}.png`) });
    await advanced.click();
    await page.getByLabel("Drawing canvas", { exact: true }).waitFor();
    assert.equal(await page.getByLabel("Edit model", { exact: true }).inputValue(), "Ideogram 4.5");
  };
  const paint = async () => {
    const rect = await page.locator(".ies-surface").boundingBox();
    await page.mouse.move(rect.x + rect.width * .35, rect.y + rect.height * .4);
    await page.mouse.down();
    await page.mouse.move(rect.x + rect.width * .6, rect.y + rect.height * .6, { steps: 10 });
    await page.mouse.up();
  };
  await open();
  assert.equal(await page.getByLabel("Edit quality", { exact: true }).inputValue(), "high");
  assert.equal(await page.getByLabel("Edit precision", { exact: true }).inputValue(), "regular");
  await page.screenshot({ path: path.join(screenshots, "ideogram-default.png") });
  await paint();
  await page.getByLabel("Selection layer", { exact: true }).click();
  await paint();
  const pixels = await page.getByLabel("Drawing canvas", { exact: true }).evaluate(canvas => canvas.toDataURL());
  await page.getByLabel("Edit prompt", { exact: true }).fill("Warm the marked area while keeping the rest unchanged.");
  await page.getByLabel("Edit model", { exact: true }).selectOption("Nano Banana 2.1");
  assert.equal(await page.getByLabel("Drawing canvas", { exact: true }).evaluate(canvas => canvas.toDataURL()), pixels);
  assert.equal(await page.getByLabel("Edit resolution", { exact: true }).inputValue(), "2K");
  assert.equal(await page.getByLabel("Edit quality", { exact: true }).count(), 0);
  assert.equal(await page.getByLabel("Edit precision", { exact: true }).count(), 0);
  await page.getByLabel("Edit resolution", { exact: true }).selectOption("4K");
  await page.screenshot({ path: path.join(screenshots, "nano-banana-drawing.png") });
  await page.getByRole("button", { name: "Generate Edit", exact: true }).click();
  await page.getByRole("button", { name: "Add Image to Canvas", exact: true }).waitFor();
  const report = JSON.parse(await page.getByLabel("QA report").textContent());
  assert.equal(report.model, "Nano Banana 2.1"); assert.equal(report.resolution, "4K");
  assert.equal(report.quality, null); assert.equal(report.editPrecision, null);
  for (const layer of ["drawing", "selection"]) {
    assert.ok(report.layers[layer].pixels > 0);
    assert.equal(report.layers[layer].width, 1536); assert.equal(report.layers[layer].height, 864);
  }
  const divider = page.getByRole("slider", { name: "Comparison divider", exact: true });
  const splitValue = async () => Number(await divider.getAttribute("aria-valuenow"));
  const dragDivider = async (percent, handle = true) => {
    const image = await page.locator(".ies-surface").boundingBox();
    const grip = await page.locator(".ies-split-handle").boundingBox();
    const x = grip.x + grip.width / 2, y = handle ? grip.y + grip.height / 2 : image.y + image.height * .25;
    await page.mouse.move(x, y); await page.mouse.down();
    await page.mouse.move(image.x + image.width * percent / 100, y, { steps: 12 });
    await page.mouse.up();
    assert.ok(Math.abs(await splitValue() - percent) <= 1);
    const after = await page.locator(".ies-surface").boundingBox();
    assert.deepEqual(after, image, "divider drag never pans the image");
    const clip = await page.locator(".ies-result").evaluate(element => parseFloat(element.style.clipPath.split(" ").at(-1)));
    assert.ok(Math.abs(clip - percent) < 1);
  };
  assert.equal(await page.getByLabel("Comparison split", { exact: true }).count(), 0);
  await dragDivider(73);
  await page.screenshot({ path: path.join(screenshots, "comparison-divider-desktop.png") });
  await page.getByLabel("Zoom in", { exact: true }).click();
  const gripSize = await page.locator(".ies-split-handle").boundingBox();
  assert.ok(Math.abs(gripSize.width - 32) < 1, "handle stays the same screen size when zoomed");
  const image = await page.locator(".ies-surface").boundingBox();
  await page.mouse.move(image.x + image.width * .25, image.y + image.height * .5);
  await page.mouse.down(); await page.mouse.move(image.x + image.width * .25 + 40, image.y + image.height * .5 + 20, { steps: 6 }); await page.mouse.up();
  assert.notEqual((await page.locator(".ies-surface").boundingBox()).x, image.x, "panning still works away from the divider");
  await dragDivider(40, false);
  await divider.focus();
  await page.keyboard.press("Home"); assert.equal(await splitValue(), 0);
  await page.keyboard.press("ArrowRight"); assert.equal(await splitValue(), 1);
  await page.keyboard.press("Shift+ArrowRight"); assert.equal(await splitValue(), 11);
  await page.keyboard.press("End"); assert.equal(await splitValue(), 100);
  await page.getByRole("button", { name: "Original", exact: true }).click();
  assert.equal(await divider.count(), 0);
  await page.getByRole("button", { name: "Edit", exact: true }).click();
  assert.equal(await divider.count(), 0);
  await page.getByRole("button", { name: "Compare", exact: true }).click();
  await divider.focus(); await page.keyboard.press("Home");
  for (let i = 0; i < 5; i++) await page.keyboard.press("Shift+ArrowRight");
  await page.getByLabel("Fit image", { exact: true }).click();
  const grip = await page.locator(".ies-split-handle").boundingBox();
  await page.mouse.move(grip.x + 16, grip.y + 16); await page.mouse.down();
  await page.mouse.move(grip.x + 100, grip.y + 16, { steps: 6 });
  assert.ok(await splitValue() > 50);
  await page.keyboard.press("Escape"); await page.mouse.up();
  assert.equal(await splitValue(), 50);
  assert.equal(await page.getByRole("alertdialog").count(), 0, "Escape cancels the drag instead of closing the editor");
  assert.deepEqual(JSON.parse(await page.getByLabel("QA report").textContent()), report, "comparison never generates or changes the edit");
  await page.getByRole("button", { name: "Add Image to Canvas", exact: true }).click();
  assert.match(await page.getByLabel("QA report").textContent(), /Accepted: copy 1536x864/);
  await open(true);
  await page.getByLabel("Edit model", { exact: true }).selectOption("OpenAI Image 2.5 Sunburst");
  await page.getByLabel("Edit quality", { exact: true }).selectOption("max");
  await page.getByLabel("Edit model", { exact: true }).selectOption("Nano Banana 2.1");
  await page.getByLabel("Edit method", { exact: true }).selectOption("sketch");
  await page.getByLabel("Blank canvas", { exact: true }).check();
  await paint();
  await page.getByRole("button", { name: "Generate Edit", exact: true }).click();
  await page.getByRole("button", { name: "Add Image to Canvas", exact: true }).waitFor();
  const sketch = JSON.parse(await page.getByLabel("QA report").textContent());
  assert.equal(sketch.blank, "true"); assert.equal(sketch.mode, "sketch"); assert.equal(sketch.resolution, "2K");
  assert.equal(sketch.layers.selection, undefined); assert.ok(sketch.layers.drawing.pixels > 0);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByLabel("Fit image", { exact: true }).click();
  const mobileImage = await page.locator(".ies-surface").boundingBox(), mobileGrip = await page.locator(".ies-split-handle").boundingBox();
  const touch = await page.context().newCDPSession(page);
  const touchPoint = { x: mobileGrip.x + mobileGrip.width / 2, y: mobileGrip.y + mobileGrip.height / 2, id: 1 };
  await touch.send("Input.dispatchTouchEvent", { type: "touchStart", touchPoints: [touchPoint] });
  for (let i = 1; i <= 8; i++) await touch.send("Input.dispatchTouchEvent", { type: "touchMove", touchPoints: [{ ...touchPoint, x: mobileImage.x + mobileImage.width * (.5 + .25 * i / 8) }] });
  await touch.send("Input.dispatchTouchEvent", { type: "touchEnd", touchPoints: [] });
  assert.ok(Math.abs(await splitValue() - 75) <= 1, "touch moves the divider on mobile");
  assert.deepEqual(await page.locator(".ies-surface").boundingBox(), mobileImage);
  await page.screenshot({ path: path.join(screenshots, "comparison-divider-mobile.png") });
  await touch.detach();
  await open(true);
  await page.getByLabel("Edit model", { exact: true }).selectOption("Nano Banana 2.1");
  await page.getByLabel("Edit resolution", { exact: true }).scrollIntoViewIfNeeded();
  const modelBox = await page.getByLabel("Edit resolution", { exact: true }).boundingBox();
  assert.ok(modelBox.x >= 0 && modelBox.x + modelBox.width <= 390);
  await page.screenshot({ path: path.join(screenshots, "nano-banana-mobile.png") });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await open(false, "atlas");
  await page.getByLabel("Edit prompt", { exact: true }).fill("Warm the scene");
  assert.ok(await page.getByRole("button", { name: "Generate Edit", exact: true }).isDisabled());
  await page.getByLabel("Edit model", { exact: true }).selectOption("OpenAI Image 2.5 Sunburst");
  assert.ok(await page.getByRole("button", { name: "Generate Edit", exact: true }).isEnabled());
  await page.getByLabel("Edit model", { exact: true }).selectOption("Nano Banana 2.1");
  assert.ok(await page.getByRole("button", { name: "Generate Edit", exact: true }).isDisabled());
  assert.deepEqual(errors, []); assert.deepEqual(apiCalls, []);
  console.log(JSON.stringify({ ok: true, screenshots, paidCalls: 0, checks: ["Ideogram default", "preserved drawing and selection", "Nano Banana resolution and mock generation", "blank sketch", "copy result", "provider guards", "mobile controls", "direct comparison dragging, zoom and pan", "comparison keyboard and Escape", "mobile touch comparison"] }, null, 2));
} finally { await browser?.close(); await server.close(); }
