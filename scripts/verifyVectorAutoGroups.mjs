import assert from "node:assert/strict";
import { mkdtemp } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import sharp from "sharp";
import { createVectorLayerService } from "../server/vector-layer-service.js";
import { startVectorQaServer } from "./vectorQaServer.mjs";

const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || "playwright");
const directory = await mkdtemp(path.join(tmpdir(), "newtnode-vector-auto-groups-qa-"));
const svg = '<svg xmlns="http://www.w3.org/2000/svg" width="400" height="300"><rect id="paper" width="400" height="300" fill="#fff"/><rect id="art" x="65" y="65" width="270" height="170" rx="12" fill="#287575"/><text id="headline" x="200" y="150" text-anchor="middle" font-family="sans-serif" font-size="38" fill="white">STUDIO</text><path id="glyph-1" d="M130 175H190V184H130Z" fill="#e8c341"/><path id="glyph-2" d="M210 175H270V184H210Z" fill="#e8c341"/></svg>';
const png = await sharp(Buffer.from(svg)).png().toBuffer();
const assets = new Map(), errors = [], forbidden = [], history = [];
let groupReviews = 0;
const service = createVectorLayerService({ readSource: async url => assets.get(url) || Buffer.from(svg), saveAssets: async (body, art) => {
  const base = `/outputs/vector-qa/${body.requestId}`;
  assets.set(`${base}.svg`, Buffer.from(art.svg)); assets.set(`${base}.png`, art.png); assets.set(`${base}-alpha.png`, art.alpha);
  return { url: `${base}.png`, svgUrl: `${base}.svg`, alphaUrl: `${base}-alpha.png` };
}, recordHistory: async item => history.push(item), describeLayers: () => assert.fail("No paid naming") });
const fixture = await startVectorQaServer({ svg, png, assets, service: { ...service, inspect: body => { if (body.prepareGroups) groupReviews++; return service.inspect(body); } } });
const browser = await chromium.launch({ headless: true, channel: "chrome" });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.setDefaultTimeout(15000); page.on("pageerror", error => errors.push(error.message)); page.on("dialog", dialog => dialog.accept());
  await page.route(/^https?:\/\/[^/]+\/api\//, route => { forbidden.push(route.request().url()); return route.abort(); });
  await page.goto(`${fixture.url}/test/browser/vector.html`);
  const button = name => page.getByRole("button", { name, exact: true });
  const modal = page.getByRole("dialog", { name: "Vector Layers editor" });
  const row = key => page.locator(`[data-layer-key="${key}"]`);
  const state = () => page.getByLabel("Vector state").textContent().then(JSON.parse);
  const ops = async () => (await state()).vectorLayerDrafts[0]?.operations || [];
  const ready = () => page.waitForFunction(() => document.querySelector('[aria-label="Vector layers"]')?.getAttribute("aria-busy") === "false");
  const pixel = (x, y) => page.locator(".vle-artwork img").evaluate(async (img, [x, y]) => { await img.decode(); const canvas = document.createElement("canvas"); canvas.width = 400; canvas.height = 300; const ctx = canvas.getContext("2d"); ctx.drawImage(img, 0, 0, 400, 300); return [...ctx.getImageData(x, y, 1, 1).data]; }, [x, y]);
  const open = async () => { await button("Edit Artwork").click(); await ready(); };
  await page.locator(".vector-generate").click(); await open();
  const sourceItem = (await state()).resultItems[0];
  assert.equal(sourceItem.vectorLayersPrepared, true); assert.equal(sourceItem.vectorGroupsPrepared, true);
  assert.equal((await ops()).length, 1); assert.equal(groupReviews, 1);
  const folders = (await ops())[0].operations.filter(op => op.type === "group");
  const text = folders.find(op => op.name === "Text"), background = folders.find(op => op.name === "Background");
  assert.deepEqual(text.keys, ["headline", "glyph-1", "glyph-2"]);
  assert.equal(await page.locator(".vle-layer-row").count(), 3);
  assert.equal(await row(text.id).locator(".vle-group-count").textContent(), "3");
  assert.equal((await pixel(0, 0))[3], 0);
  assert.deepEqual(await pixel(150, 179), [232, 195, 65, 255]);
  await button("Hide Text").click(); await ready(); assert.deepEqual(await pixel(150, 179), [40, 117, 117, 255]);
  await button("Show Text").click(); await ready(); assert.deepEqual(await pixel(150, 179), [232, 195, 65, 255]);
  await button("Show Background").click(); await ready(); assert.equal((await pixel(0, 0))[3], 255);
  await button("Hide Background").click(); await ready(); assert.equal((await pixel(0, 0))[3], 0);
  await button("Expand Text").click(); assert.equal(await row("headline").count(), 1);
  await button("Collapse Text").click(); assert.equal(await row("headline").count(), 0);
  await row(text.id).click(); await page.locator(".vle-selection").waitFor();
  await page.locator(".vle-artwork").focus(); await page.keyboard.press("Shift+ArrowRight"); await ready();
  assert.equal((await ops()).at(-1).type, "transform");
  await page.keyboard.press("Meta+z"); await ready(); assert.notEqual((await ops()).at(-1).type, "transform");
  await row(text.id).locator(".vle-layer-name").dblclick();
  await page.getByLabel(`Layer name ${text.id}`, { exact: true }).fill("Brand lettering");
  await page.getByLabel(`Layer name ${text.id}`, { exact: true }).press("Enter"); await ready();
  await modal.screenshot({ path: path.join(directory, "auto-groups-desktop.png") });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await modal.evaluate(el => el.scrollWidth <= el.clientWidth + 1));
  await modal.screenshot({ path: path.join(directory, "auto-groups-mobile.png") });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await modal.getByRole("button", { name: "Save Version", exact: true }).click(); await modal.waitFor({ state: "detached" });
  const edited = (await state()).resultItems[1];
  assert.equal(edited.vectorGroupsPrepared, true); assert.equal(edited.vectorLayersPrepared, true);
  assert.deepEqual(edited.vectorBackgroundKeys, [background.id]);
  assert.equal((await sharp(assets.get(edited.url)).ensureAlpha().raw().toBuffer())[3], 0);
  assert.match(assets.get(edited.svgUrl).toString(), /Brand lettering/);
  await button("Save / Reopen").click(); await open();
  assert.equal(groupReviews, 1, "saved versions keep grouping review");
  assert.equal(await row(text.id).locator(".vle-layer-name").textContent(), "Brand lettering");
  await button("Cancel").click(); await modal.waitFor({ state: "detached" });

  // A new result receives one automatic review, and Cancel never reapplies it.
  await page.locator(".vector-generate").click();
  await page.waitForFunction(() => JSON.parse(document.querySelector('[aria-label="Vector state"]').textContent).resultItems.length === 3);
  await open(); assert.equal(groupReviews, 2);
  await button("Undo layer edit").click(); await ready(); assert.equal(await page.locator(".vle-layer-row").count(), 5);
  await button("Redo layer edit").click(); await ready(); assert.equal(await page.locator(".vle-layer-row").count(), 3);
  await button("Cancel").click(); await modal.waitFor({ state: "detached" });
  await button("Save / Reopen").click(); await open(); assert.equal(groupReviews, 2);
  assert.equal(await page.locator(".vle-layer-row").count(), 5);
  assert.equal((await pixel(0, 0))[3], 255);
  const calls = JSON.parse(await page.getByLabel("Provider calls").textContent());
  assert.equal(calls.generate, 2); assert.equal(calls.naming || 0, 0);
  assert.deepEqual(errors, []); assert.deepEqual(forbidden, []);
  console.log(JSON.stringify({ ok: true, directory, localSaves: history.length, paidCalls: 0, checks: ["automatic Text/Background folders", "safe labeled glyphs", "expand/collapse", "folder visibility", "transparent pixels", "move/undo", "rename/save", "desktop/mobile", "review once per result", "Cancel and project reopen"] }, null, 2));
} finally { await browser.close(); await fixture.close(); }
